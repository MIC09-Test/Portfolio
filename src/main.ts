// ------------------------------------------------------------
// Tiny DOM helper: el("p", { class: "x" }, "text", childNode…)
// ------------------------------------------------------------
type Child = Node | string;

function el<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  attrs: Record<string, string> = {},
  ...children: Child[]
): HTMLElementTagNameMap[K] {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) node.setAttribute(k, v);
  for (const c of children) node.append(c);
  return node;
}

// Every i in his name is a bulb. Wrapping each one gives the stylesheet a
// glass to put a filament behind, and gives the switch beside them something
// to feed — in the cave they are, quite literally, the lights that are off.
function bulbName(name: string): Child[] {
  return [...name].map((ch) =>
    ch.toLowerCase() === "i" ? el("span", { class: "bulb" }, ch) : ch,
  );
}

function chips(items: string[]): HTMLElement {
  return el(
    "div",
    { class: "chips" },
    ...items.map((i) => el("span", { class: "chip" }, i)),
  );
}

function sectionLabel(num: string, title: string): HTMLElement {
  return el(
    "div",
    { class: "section-label" },
    el("span", { class: "num" }, num),
    el("h2", {}, title),
  );
}

