// Torch mode: the character is the cursor, the torch the light.
// ------------------------------------------------------------
const hint = document.getElementById("hint")!;
const toggle = lightSwitch;

const isTouch = "ontouchstart" in window || navigator.maxTouchPoints > 0;
if (isTouch) {
  document.body.classList.add("touch");
  // No Esc key on a phone — the ☀ button is the lifeline there instead.
  hint.textContent = "◀ ▶ walk · ▲ jump · ▼ descend · ☀ lights";
}

const engine = new Engine(
  () => {
    hint.style.opacity = "0";
  },
  // His torch knocked the switch by his name: that is the way out of the cave.
  () => lightUp(),
);
const sleeper = new Sleeper(deskCanvas);

// Visitors land on the plain scrolling page; "Lights off" opts into the
// cave. On unless this visitor has explicitly turned the lights off before.
const LIGHTS_KEY = "lights-on";
let lightsOn = localStorage.getItem(LIGHTS_KEY) !== "0";

function applyLights(): void {
  // Both modes share the same layout, so the camera position and the scroll
  // position mean the same thing — hand one to the other and the toggle
  // keeps the visitor exactly where they were looking.
  const cameraWas = engine.cameraY;
  const scrollWas = window.scrollY;

  document.body.classList.toggle("lights-on", lightsOn);
  // The switch shows its state by the way the rocker sits; this is that same
  // state said out loud, and the tooltip for anyone unsure what the plate is.
  const label = lightsOn ? "Lights off" : "Lights on";
  toggle.setAttribute("aria-label", label);
  toggle.setAttribute("title", label);
  toggle.setAttribute("aria-pressed", lightsOn ? "false" : "true");

  if (lightsOn) {
    // The view doesn't move — it's already showing this spot — so the
    // animation is the darkness lifting off it. Keep the light canvas on
    // screen for that until the lift finishes.
    document.body.classList.add("lights-rising");
    window.scrollTo({ top: cameraWas, behavior: "instant" });
    sleeper.setEnabled(true);
    engine.beginExit(() => document.body.classList.remove("lights-rising"));
  } else {
    document.body.classList.remove("lights-rising");
    sleeper.setEnabled(false);
    engine.setEnabled(true, scrollWas);
  }
}

function lightUp(): void {
  if (lightsOn) return;
  lightsOn = true;
  localStorage.setItem(LIGHTS_KEY, "1");
  applyLights();
}

toggle.addEventListener("click", () => {
  // One-way. In the cave the switch stops being a control and becomes a thing
  // on a wall: the only way to throw it is to get up there and hit it. CSS
  // takes the pointer off it too, but the guard is what actually decides.
  if (!lightsOn) return;
  lightsOn = false;
  localStorage.setItem(LIGHTS_KEY, "0");
  applyLights();
  toggle.blur();
});

// The lifeline. Reaching the switch is the way back and the launcher makes it
// a short trip, but nobody should be stuck in a 95% dark room because they
// came to read a CV and not to platform for it.
window.addEventListener("keydown", (e) => {
  if (e.key === "Escape") lightUp();
});
// The same lifeline for anyone without a keyboard.
document.getElementById("btn-lights")?.addEventListener("click", () => lightUp());

applyLights();

// ------------------------------------------------------------
// Reveal-on-scroll, lit page only — the CSS gates it, so the cave
// is untouched. Down there the darkness canvas already decides
// what can be seen and the text stays at full strength behind it.
// The observer keeps running in both modes so the state is already
// right the moment the lights come back on.
// ------------------------------------------------------------
// Sections re-arm once they are fully off screen, so the reveal plays
// again on the way back up. The two thresholds give it hysteresis: it
// shows at 15% in and only resets at 0%, never flickering at the edge.
const revealObserver = new IntersectionObserver(
  (entries) => {
    for (const entry of entries) {
      const el = entry.target as HTMLElement;

      if (entry.intersectionRatio >= 0.15) {
        el.classList.add("is-visible");
      } else if (entry.intersectionRatio === 0) {
        // Re-arm pointing at the edge it just left by, so the next pass
        // slides in from the direction the visitor is coming from.
        const leftAbove =
          entry.boundingClientRect.bottom <= (entry.rootBounds?.top ?? 0);
        el.style.setProperty("--reveal-dir", leftAbove ? "-1" : "1");
        el.classList.remove("is-visible");
      }
    }
  },
  { threshold: [0, 0.15], rootMargin: "0px 0px -10% 0px" },
);
document.querySelectorAll(".reveal").forEach((el) => revealObserver.observe(el));
